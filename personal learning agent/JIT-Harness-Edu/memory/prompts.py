"""教育记忆的类别和抽取指令。

mem0 开源版（2.x）用一个通用的“记忆抽取”提示词从对话里抽事实，并支持追加自定义指令
（config 里的 custom_instructions，或 add() 时传 prompt）。这里的指令把它改造成
“教育体验抽取器”：只记对以后教学有用的东西，每条带【类别】前缀，一律中文。
"""

# 学生记忆的类别（user_id = 学生）
LEARNER_CATEGORIES = {
    "背景信息": "年级/专业、学习目的、已有基础、可用时间",
    "学习偏好": "喜欢或不喜欢的讲解方式、节奏、呈现形式（图/例子/公式）、兴趣点",
    "知识掌握": "明确掌握或没掌握的具体知识点，以及证据（答对/答错了什么）",
    "易错点": "具体的错误或误解：错在哪、是怎么想错的",
    "有效技巧": "对这个学生有效或无效的教学方法，以及证据（用了什么、他的反应）",
    "学习状态": "情绪、动机、专注度、自信心及其变化",
    "学习进度": "学到哪里、下次从哪里继续",
}

# 跨学生的教学经验（agent_id = edu_teacher）
EXPERIENCE_CATEGORY = "教学经验"

EDU_MEMORY_INSTRUCTIONS = "\n".join([
    "你在为一个 AI 家教系统维护“学生学习记忆”。对话中 user 是学生，assistant 是导师。",
    "只抽取对今后教这个学生有用的信息，类别只有以下七种：",
    *[f"- {name}：{desc}" for name, desc in LEARNER_CATEGORIES.items()],
    "规则：",
    "1. 每条记忆的 text 必须以【类别】开头，例如：【易错点】学生做分数除法时忘记把除数取倒数，直接分子除分子。",
    "2. 一律用简体中文，用“学生”指代 user；写成独立完整的一句话，包含具体知识点和证据。",
    "3. 学生的作答表现记为“知识掌握”或“易错点”；导师用了某种方法且学生反应明显时，记为“有效技巧”。",
    "4. 不要记录：寒暄、导师讲解的知识内容本身、没有证据的猜测、导师自己的承诺。",
    "5. 没有值得记的内容就返回空列表。",
])
